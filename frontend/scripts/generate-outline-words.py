"""Generate merged DM Sans outlines for the decorative landing typography.

Optional authoring tools (not needed by the app or its build):
    pip install 'fonttools[woff]==4.67.0' skia-pathops==0.9.2
    python scripts/generate-outline-words.py
"""

import json
from math import ceil
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.ttLib.removeOverlaps import removeOverlaps
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "node_modules/@fontsource-variable/dm-sans/files/dm-sans-latin-wght-normal.woff2"
WORDS = {
    "intro": "KREA 2",
    "models": "TURBO",
    "loras": "LORA",
    "references": "REFERENCE",
    "create": "CREATE",
}

font = instantiateVariableFont(TTFont(FONT), {"wght": 400})
cmap = font.getBestCmap()
used_glyphs = sorted({cmap[ord(char)] for word in WORDS.values() for char in word})

# A stroke exposes internal overlaps that are invisible when the font is filled.
# Boolean-union each glyph before extracting its outer edge and counters.
removeOverlaps(font, used_glyphs, ignoreErrors=False)
assert font["glyf"][cmap[ord("A")]].numberOfContours == 2
assert font["glyf"][cmap[ord("R")]].numberOfContours == 2

glyph_set = font.getGlyphSet()
scale = 240 / font["head"].unitsPerEm


def number(value):
    return f"{value:.3f}".rstrip("0").rstrip(".") or "0"


outlines = {}
for identifier, label in WORDS.items():
    pen = SVGPathPen(glyph_set, ntos=number)
    cursor = 12
    for index, char in enumerate(label):
        name = cmap[ord(char)]
        glyph_set[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cursor, 250)))
        cursor += font["hmtx"][name][0] * scale
        if index < len(label) - 1:
            cursor += 4
    outlines[identifier] = {
        "label": label,
        "width": ceil(cursor + 12),
        "path": pen.getCommands(),
    }

output = ROOT / "src/lib/outline-words.ts"
output.write_text(
    "// Generated by scripts/generate-outline-words.py.\n"
    "// DM Sans regular 400; intersecting glyph contours have been merged.\n"
    f"export const outlineWords = {json.dumps(outlines, indent=2)} as const;\n"
)
print(f"Generated {len(outlines)} words ({output.stat().st_size:,} bytes); A and R each have two clean contours.")
